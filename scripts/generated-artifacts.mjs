import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const manifestPath = resolve(root, 'generated-artifacts.json');
const expectedEngineCommit = 'a26aa79de5dfd2f890c9f28aae858e4653cc78d5';
const expectedJszipVersion = '3.10.1';
const expectedJszipIntegrity =
  'sha512-xXDvecyTpGLrqFrvkrUSoxxfJI5AH7U8zxxtVclpsUtMCq4JQ290LY8AW5c7Ggnr/Y/oK+bQMbqK2qmtk3pN4g==';

const sha256 = (contents) =>
  createHash('sha256').update(contents).digest('hex');

const normalizeSource = (contents) =>
  `${contents.toString('utf8').replace(/\r\n?/g, '\n').replace(/\n+$/u, '')}\n`;

const serialize = (contents) =>
  JSON.stringify(contents)
    .replaceAll('\u2028', '\\u2028')
    .replaceAll('\u2029', '\\u2029');

const enginePath = resolve(root, 'vendor/epub.js');
const engineCommit = execFileSync(
  'git',
  ['-C', enginePath, 'rev-parse', 'HEAD'],
  { encoding: 'utf8' }
).trim();

if (engineCommit !== expectedEngineCommit) {
  throw new Error(
    `Expected EPUB.js submodule ${expectedEngineCommit}, received ${engineCommit}`
  );
}

let jszipPackagePath;
let jszipPackage;
try {
  jszipPackagePath = require.resolve('jszip/package.json');
  jszipPackage = JSON.parse(readFileSync(jszipPackagePath, 'utf8'));
} catch {
  throw new Error('JSZip is missing. Run `npm ci --ignore-scripts` first.');
}

if (jszipPackage.version !== expectedJszipVersion) {
  throw new Error(
    `Expected JSZip ${expectedJszipVersion}, received ${jszipPackage.version}`
  );
}

const packageLock = JSON.parse(
  readFileSync(resolve(root, 'package-lock.json'), 'utf8')
);
const lockedJszip = packageLock.packages?.['node_modules/jszip'];
if (
  lockedJszip?.version !== expectedJszipVersion ||
  lockedJszip?.integrity !== expectedJszipIntegrity
) {
  throw new Error('package-lock.json does not contain the approved JSZip pin');
}

const definitions = {
  epubjs: {
    input: resolve(enginePath, 'dist/epub.min.js'),
    output: resolve(root, 'src/epubjs.ts'),
    source: `masonbrothers/epub.js@${engineCommit}:dist/epub.min.js`,
  },
  jszip: {
    input: resolve(dirname(jszipPackagePath), 'dist/jszip.min.js'),
    output: resolve(root, 'src/jszip.ts'),
    source: `jszip@${jszipPackage.version}:dist/jszip.min.js`,
  },
};

const renderArtifact = ({ input, source }) => {
  let normalized;
  try {
    normalized = normalizeSource(readFileSync(input));
  } catch {
    throw new Error(
      `Missing generated input ${relative(root, input)}. ` +
        'Install nested engine dependencies and run `npm run build:epubjs-source`.'
    );
  }

  const sourceHash = sha256(normalized);
  const module = [
    '// Generated by scripts/generated-artifacts.mjs. Do not edit.',
    `// Source: ${source}`,
    `// Normalized source SHA-256: ${sourceHash}`,
    '// Normalization: LF line endings and exactly one terminal newline.',
    '',
    `export default ${serialize(normalized)};`,
    '',
  ].join('\n');

  return { module, moduleHash: sha256(module) };
};

const rendered = Object.fromEntries(
  Object.entries(definitions).map(([name, definition]) => [
    name,
    renderArtifact(definition),
  ])
);

const manifest = `${JSON.stringify(
  {
    schemaVersion: 1,
    engine: {
      repository: 'https://github.com/masonbrothers/epub.js.git',
      submodulePath: 'vendor/epub.js',
      commit: engineCommit,
      artifact: 'src/epubjs.ts',
      sha256: rendered.epubjs.moduleHash,
    },
    jszip: {
      version: jszipPackage.version,
      integrity: lockedJszip.integrity,
      artifact: 'src/jszip.ts',
      sha256: rendered.jszip.moduleHash,
    },
    licenses: [
      'licenses/EPUBJS-BSD-2-Clause.txt',
      'licenses/EPUBJS-BUNDLED-MIT-NOTICES.txt',
      'licenses/JSZIP-MIT.txt',
      'licenses/LOCALFORAGE-APACHE-2.0.txt',
      'licenses/PAKO-MIT.txt',
    ],
  },
  null,
  2
)}\n`;

const [mode, target] = process.argv.slice(2);
if (!['generate', 'check'].includes(mode) || !rendered[target]) {
  throw new Error(
    'Usage: node scripts/generated-artifacts.mjs <generate|check> <epubjs|jszip>'
  );
}

const expected = rendered[target].module;
const output = definitions[target].output;

if (mode === 'generate') {
  writeFileSync(output, expected);
  writeFileSync(manifestPath, manifest);
  console.log(`${relative(root, output)} ${sha256(expected)}`);
  console.log(`${relative(root, manifestPath)} ${sha256(manifest)}`);
} else {
  let actual;
  let actualManifest;
  try {
    actual = readFileSync(output, 'utf8');
    actualManifest = readFileSync(manifestPath, 'utf8');
  } catch {
    throw new Error(
      'Generated artifacts are missing. Run `npm run generate:generated`.'
    );
  }

  if (actual !== expected) {
    throw new Error(
      `${relative(root, output)} is stale; run npm run generate:${target}`
    );
  }
  if (actualManifest !== manifest) {
    throw new Error(
      'generated-artifacts.json is stale; run npm run generate:generated'
    );
  }

  console.log(`${relative(root, output)} verified ${sha256(actual)}`);
}
